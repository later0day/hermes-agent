// The backend's fallback description for a field without a hand-written one: the dot-path
// humanized by Python's str.title() (hermes_cli/web_server_config.py::_build_schema_from_config).
function autoDescription(schemaKey: string): string {
  return schemaKey
    .replace(/\./g, " → ")
    .replace(/_/g, " ")
    .replace(/[A-Za-z]+/g, (w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase());
}

function humanize(segment: string): string {
  return autoDescription(segment);
}

function zhLeafLabel(schemaKey: string): string | undefined {
  const leaf = schemaKey.split(".").pop() ?? schemaKey;
  return ZH_CONFIG_FIELDS[schemaKey]?.label ?? ZH_CONFIG_LEAVES[leaf];
}

